
from rest_framework import serializers

from .models import RawMaterial

from byproducts.models import ByProduct


class RawMaterialSerializer(serializers.ModelSerializer):

    material_type_display = serializers.CharField(
        source='get_material_type_display',
        read_only=True
    )

    actual_yield = serializers.FloatField(
        read_only=True
    )

    waste_quantity = serializers.FloatField(
        read_only=True
    )

    processing_completed = serializers.SerializerMethodField()

    byproducts = serializers.SerializerMethodField()

    class Meta:
        model = RawMaterial

        fields = [
            'id',
            'product_id',

            'material_type',
            'material_type_display',

            'quantity',
            'process_stage',

            'lower_yield',
            'predicted_yield',
            'upper_yield',

            'actual_yield',
            'waste_quantity',

            'processing_completed',

            'byproducts',

            'submitted_at'
        ]

    # =========================================================
    # PROCESSING COMPLETED
    # =========================================================

    def get_processing_completed(self, obj):

        byproducts = ByProduct.objects.filter(
            raw_material=obj
        )

        # No by-product means Scrap Team has not started
        if not byproducts.exists():
            return False

        # Every generated by-product must be completed
        return not byproducts.exclude(
            status='completed'
        ).exists()

    # =========================================================
    # BY-PRODUCTS
    # =========================================================

    def get_byproducts(self, obj):

        byproducts = ByProduct.objects.filter(
            raw_material=obj
        )

        return [
            {
                'id': byproduct.id,

                'byproduct_type':
                    byproduct.byproduct_type,

                'quantity':
                    byproduct.quantity,

                'status':
                    byproduct.status,

                'potential_applications':
                    byproduct.potential_applications,

            }

            for byproduct in byproducts
        ]
